"""Flatten nanopubs/audience.json into the AI plain-language summary nanopubs.

One summary per audience, about the chain apex (nanopubs/PUBLISHED.md), in the
"Heading — paragraph" layout of earlier summaries on the network. Writes
nanopubs/audience-summaries.md with each text and a Nanodash link that pre-fills the
template, so the published text is exactly the text of the story page's tab.
"""

import json
import sys
from pathlib import Path
from urllib.parse import urlencode

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_story import apex_from_published  # noqa: E402

TEMPLATE = "https://w3id.org/np/RAWy6z_pULiaGYdk0GFQMxtnOog1KZRCkR9ywqX0YF84M"
MAX_CHARS = 2000  # the template's regex: [\s\S]{0,2000}
AUDIENCE = {  # the template's own vocabulary (RAHrBp6pVKHi4icalxhDptDJvQ4ObEKCBOcnzvEhiZhxs)
    "citizens": "http://www.wikidata.org/entity/Q2388316",
    "schools": "https://w3id.org/sciencelive/o/terms/audience/secondary-13-16",
}
NANODASH = "https://nanodash.knowledgepixels.com/publish"


def flatten(aud: dict) -> str:
    parts = [aud["title"], aud["lead"]]
    parts += [f'{s["h"]} — {s["p"]}' for s in aud["sections"]]
    parts.append(aud["closing"])
    return "\n\n".join(parts)


def main(root: Path = Path(".")) -> None:
    apex = apex_from_published(root)
    if not apex:
        raise SystemExit("No chain apex in nanopubs/PUBLISHED.md.")
    audiences = json.loads((root / "nanopubs" / "audience.json").read_text())["audiences"]
    out = ["# AI plain-language summaries — to publish",
           "",
           f"Generated by `scripts/audience_summaries.py` from `nanopubs/audience.json`. Template: <{TEMPLATE}>.",
           f"About: <{apex}> (paste this full URI if the form does not keep it).",
           ""]
    for aud in audiences:
        text = flatten(aud)
        if len(text) > MAX_CHARS:
            raise SystemExit(f"{aud['id']}: {len(text)} characters, the template allows {MAX_CHARS}.")
        link = NANODASH + "?" + urlencode({"template": TEMPLATE, "param_subject": apex,
                                           "param_audience": AUDIENCE[aud["id"]], "param_text": text})
        out += [f"## {aud['label']} ({len(text)} characters)", "",
                f"Audience: <{AUDIENCE[aud['id']]}>", "",
                f"[Open the pre-filled form]({link})", "",
                "```text", text, "```", ""]
        print(f"{aud['id']}: {len(text)} characters")
    (root / "nanopubs" / "audience-summaries.md").write_text("\n".join(out))
    print("wrote nanopubs/audience-summaries.md")


if __name__ == "__main__":
    main()
